#!/bin/sh
# Dumps the subset of PROJ's proj.db that proj4j transcodes, in sqlite3's `.mode quote` form.
#
# Build-time only: run by the `regen-db` Maven profile, never by a default build. A default
# `mvn install` uses the checked-in index and verifies its SHA-256, so a machine with no sqlite3
# builds successfully -- and cannot silently fall back to a stale artifact.
#
# Usage: dump.sh <proj.db> <output>
set -eu

DB="${1:?usage: dump.sh <proj.db> <output>}"
OUT="${2:?usage: dump.sh <proj.db> <output>}"

if ! command -v sqlite3 >/dev/null 2>&1; then
    echo "dump.sh: sqlite3 not found; omit -Pregen-db to build from the checked-in database" >&2
    exit 1
fi

if [ ! -f "$DB" ]; then
    echo "dump.sh: $DB does not exist." >&2
    echo "  proj.db is not checked into PROJ; it is generated by sqlite3 from the 52 files listed in" >&2
    echo "  data/sql_filelist.cmake. Point -Dproj.db.source at a built one (Homebrew's proj 9.8.1" >&2
    echo "  installs it at /opt/homebrew/share/proj/proj.db), or build it from a PROJ 9.8.1 checkout." >&2
    exit 1
fi

mkdir -p "$(dirname "$OUT")"

# Every table below is dumped whole with `select *`, and the generator maps columns *by header name*.
# That is deliberate: it means this script carries no column list to drift out of step with the Java
# side, and an upstream schema change that removes a column proj4j needs fails loudly in the
# generator instead of silently shifting every field by one.
#
# Row order here does not matter. The generator imposes a total order over every table and index, and
# that -- not sqlite's output order -- is what makes the result byte-reproducible.
{
    echo ".bail on"
    echo ".mode quote"
    echo ".headers on"
    for t in \
        metadata \
        unit_of_measure \
        celestial_body \
        ellipsoid \
        prime_meridian \
        geodetic_datum \
        vertical_datum \
        geodetic_datum_ensemble_member \
        vertical_datum_ensemble_member \
        coordinate_system \
        axis \
        geodetic_crs \
        projected_crs \
        vertical_crs \
        compound_crs \
        engineering_crs \
        conversion_method \
        conversion_param \
        conversion_table \
        coordinate_operation_method \
        helmert_transformation_table \
        grid_transformation \
        other_transformation \
        concatenated_operation \
        concatenated_operation_step \
        usage \
        extent \
        grid_alternatives \
        alias_name \
        supersession \
        deprecation
    do
        echo ".print #TABLE $t"
        echo "select * from $t;"
    done
    echo ".print #END"
} | sqlite3 "$DB" > "$OUT"

echo "dump.sh: wrote $OUT ($(wc -c < "$OUT" | tr -d ' ') bytes) from $DB"
