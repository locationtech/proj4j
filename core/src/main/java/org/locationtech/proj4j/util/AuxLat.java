    /**
     * Computes the {@value #ORDER} Fourier coefficients for converting the auxiliary
     * latitude {@code auxin} (called zeta upstream) to {@code auxout} (eta).
     *
     * <p>Port of {@code pj_auxlat_coeffs}. {@code F[l] = C[eta,zeta] . P(n)} where
     * {@code P(n) = [n, n^2, n^3, ...]^T}.
     *
     * <p><b>The n-squared split is load bearing.</b> When both latitudes are
     * {@code <= RECTIFYING} (i.e. the {@code phi <-> mu} pair, the only such pair with
     * a populated table) the coefficient of each Fourier term is a polynomial in
     * {@code n^2} with 12 stored constants; for every other supported pair it is a
     * polynomial in {@code n} with 21. That branch is at
     * {@code 9.8.1:src/latitudes.cpp:342}.
     *
     * @param n      the third flattening, {@code (a - b) / (a + b)}
     * @param auxin  the input auxiliary latitude, one of the constants on this class
     * @param auxout the output auxiliary latitude
     * @param f      destination, at least {@value #ORDER} long; the first
     *               {@value #ORDER} elements are written
     * @throws IllegalArgumentException if either latitude is out of range, or the
     *                                  conversion between them is not one of the
     *                                  eight tabulated
     */
    public static void coeffs(double n, int auxin, int auxout, double[] f) {
        if (!(auxin >= 0 && auxin < NUMBER && auxout >= 0 && auxout < NUMBER)) {
            throw new IllegalArgumentException(
                    "Bad specification for auxiliary latitude: auxin=" + auxin
                            + " auxout=" + auxout);
        }
        final int k = NUMBER * auxout + auxin;
        int o = PTRS[k];
        if (o == PTRS[k + 1]) {
            throw new IllegalArgumentException(
                    "Unsupported conversion between auxiliary latitudes: "
                            + name(auxin) + " -> " + name(auxout));
        }
        double d = n;
        if (auxin <= RECTIFYING && auxout <= RECTIFYING) {
            final double n2 = n * n;
            for (int l = 0; l < ORDER; ++l) {
                final int m = (ORDER - l - 1) / 2; // order of polynomial in n^2
                f[l] = d * polyval(n2, COEFFS, o, m);
                o += m + 1;
                d *= n;
            }
        } else {
            for (int l = 0; l < ORDER; ++l) {
                final int m = ORDER - l - 1; // order of polynomial in n
                f[l] = d * polyval(n, COEFFS, o, m);
                o += m + 1;
                d *= n;
            }
        }
        // Invariant from upstream's commented-out assert: o == PTRS[k + 1].
    }

    /**
     * Convenience form of {@link #coeffs(double, int, int, double[])} returning a
     * freshly allocated array of length {@value #ORDER}.
     *
     * @param n      the third flattening
     * @param auxin  the input auxiliary latitude
     * @param auxout the output auxiliary latitude
     * @return the {@value #ORDER} Fourier coefficients
     */
    public static double[] coeffs(double n, int auxin, int auxout) {
        double[] f = new double[ORDER];
        coeffs(n, auxin, auxout, f);
        return f;
    }

    /**
     * Reports whether the given conversion has a tabulated coefficient matrix.
     *
     * @param auxin  the input auxiliary latitude
     * @param auxout the output auxiliary latitude
     * @return true if {@link #coeffs(double, int, int, double[])} will succeed
     */
    public static boolean isSupported(int auxin, int auxout) {
        if (!(auxin >= 0 && auxin < NUMBER && auxout >= 0 && auxout < NUMBER)) {
            return false;
        }
        final int k = NUMBER * auxout + auxin;
        return PTRS[k] != PTRS[k + 1];
    }

    /**
     * Evaluates {@code sum(p[offset + i] * x^i, i, 0, n)} by Horner's method.
     * Port of {@code pj_polyval}; note {@code p} holds {@code n + 1} usable elements
     * from {@code offset}, and {@code n < 0} yields 0.
     *
     * @param x      the argument
     * @param p      the coefficient array
     * @param offset index in {@code p} of the constant term
     * @param n      the degree
     * @return the polynomial value
     */
    public static double polyval(double x, double[] p, int offset, int n) {
        double y = n < 0 ? 0.0 : p[offset + n];
        for (; n > 0; ) {
            y = y * x + p[offset + --n];
        }
        return y;
    }

    /**
     * Evaluates {@code sum(p[i] * x^i, i, 0, p.length - 1)} by Horner's method.
     *
     * @param x the argument
     * @param p the coefficient array, constant term first
     * @return the polynomial value
     */
    public static double polyval(double x, double[] p) {
        return polyval(x, p, 0, p.length - 1);
    }

    /**
     * The rectifying radius, {@code (quarter meridian) / ((pi/2) * a)}. Port of
     * {@code pj_rectifying_radius}: the expansion of
     * {@code (quarter meridian) / ((a+b)/2 * pi/2)} as a series in {@code n^2},
     * divided by {@code 1 + n}. Its accuracy matches the auxiliary-latitude series.
     *
     * @param n the third flattening
     * @return the rectifying radius, in units of the semi-major axis
     */
    public static double rectifyingRadius(double n) {
        return polyval(n * n, COEFF_RAD, 0, 3) / (1.0 + n);
    }

    /**
     * The third flattening {@code n = (a - b) / (a + b)} derived from the squared
     * first eccentricity.
     *
     * <p>Upstream ({@code ell_set.cpp:550-630}) computes {@code n = pow(tan(alpha/2), 2)}
     * with {@code alpha = asin(e)} — three platform-dependent libm calls. Since
     * {@code tan(alpha/2) = e / (1 + sqrt(1 - e^2))} exactly, this equals
     * {@code es / (1 + sqrt(1 - es))^2}, computed here with a single exactly-rounded
     * {@code sqrt}. The deviation is at most 2 ulp on {@code n}, propagating to about
     * 1e-19 rad, forty orders of magnitude inside the tightest conformance bar; in
     * exchange every derived coefficient becomes bit-reproducible across x86-64 and
     * AArch64, which cannot be achieved any other way.
     *
     * @param es the squared first eccentricity
     * @return the third flattening
     */
    public static double thirdFlattening(double es) {
        final double t = 1.0 + Math.sqrt(1.0 - es);
        return es / (t * t);
    }

    private static String name(int aux) {
        switch (aux) {
            case GEOGRAPHIC: return "GEOGRAPHIC(phi)";
            case PARAMETRIC: return "PARAMETRIC(beta)";
            case GEOCENTRIC: return "GEOCENTRIC(theta)";
            case RECTIFYING: return "RECTIFYING(mu)";
            case CONFORMAL:  return "CONFORMAL(chi)";
            case AUTHALIC:   return "AUTHALIC(xi)";
            default:         return "UNKNOWN(" + aux + ")";
        }
    }
