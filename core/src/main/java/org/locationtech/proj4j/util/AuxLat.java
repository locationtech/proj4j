package org.locationtech.proj4j.util;

/**
 * Auxiliary-latitude series coefficients, a port of PROJ 9.8.1's
 * {@code src/latitudes.cpp:238-420} ({@code pj_auxlat_coeffs}, {@code pj_polyval},
 * {@code pj_rectifying_radius}).
 *
 * <p>The framework is Karney's, <i>On auxiliary latitudes</i>, Survey Review 56,
 * 165-180 (2024). Conversions between any pair of auxiliary latitudes are Fourier
 * series in the source latitude whose coefficients are Taylor series in the third
 * flattening {@code n}, truncated at order 6. That suffices for full double
 * precision for {@code |f| <= 1/150} and is satisfactory for {@code |f| <= 1/50}.
 *
 * <p>The coefficient table is machine generated by the Maxima script
 * {@code auxlat.mac} bundled with GeographicLib, and is transcribed here verbatim
 * from upstream as <em>exact rational expressions</em> rather than decimal literals,
 * so that each entry is the correctly-rounded {@code double} nearest the exact
 * rational on every platform.
 *
 * <p>Only the upper triangular portion of each matrix is stored, and for the
 * conversions among {@code phi, beta, theta, mu} half the coefficients vanish (those
 * Taylor series are expansions in {@code n^2}), so the zero entries are excluded too.
 * All eight supported matrices are concatenated into one flat 150-element array,
 * indexed through {@link #PTRS}.
 *
 * <p><b>Only 8 of the 36 conversions are populated</b>, namely
 * {@code phi <-> mu} (meridian distance), {@code phi <-> chi} (transverse Mercator),
 * {@code phi <-> xi} (authalic latitude) and {@code chi <-> mu} (transverse Mercator).
 * Any other pair throws {@link IllegalArgumentException}.
 *
 * <p><b>Math vs StrictMath:</b> this class performs only {@code + - * /} and
 * {@link Math#sqrt}, all of which IEEE-754 specifies as exactly rounded, so every
 * coefficient produced here is bit-reproducible across architectures without needing
 * {@code StrictMath}. That is the whole point of deriving {@code n} from
 * {@code es} with one {@code sqrt} (see {@link #thirdFlattening}) instead of
 * upstream's {@code pow(tan(asin(e)/2), 2)}, which routes through three
 * platform-dependent libm calls.
 *
 * @see Clenshaw6
 */
