    /**
     * Evaluates {@code StrictMath.<fn>(x)}.
     *
     * @param fn one of {@link #UNARY}
     * @param x  the argument
     * @return the result
     */
    static double strictUnary(String fn, double x) {
        if ("sin".equals(fn)) return StrictMath.sin(x);
        if ("cos".equals(fn)) return StrictMath.cos(x);
        if ("tan".equals(fn)) return StrictMath.tan(x);
        if ("asin".equals(fn)) return StrictMath.asin(x);
        if ("acos".equals(fn)) return StrictMath.acos(x);
        if ("atan".equals(fn)) return StrictMath.atan(x);
        if ("exp".equals(fn)) return StrictMath.exp(x);
        if ("log".equals(fn)) return StrictMath.log(x);
        if ("log10".equals(fn)) return StrictMath.log10(x);
        if ("log1p".equals(fn)) return StrictMath.log1p(x);
        if ("expm1".equals(fn)) return StrictMath.expm1(x);
        if ("sinh".equals(fn)) return StrictMath.sinh(x);
        if ("cosh".equals(fn)) return StrictMath.cosh(x);
        if ("tanh".equals(fn)) return StrictMath.tanh(x);
        if ("cbrt".equals(fn)) return StrictMath.cbrt(x);
        if ("sqrt".equals(fn)) return StrictMath.sqrt(x);
        throw new IllegalArgumentException("unknown unary function: " + fn);
    }

    /**
     * Evaluates {@code Math.<fn>(x)} - the non-strict counterpart, used only as the negative
     * control.
     *
     * @param fn one of {@link #UNARY}
     * @param x  the argument
     * @return the result
     */
    static double mathUnary(String fn, double x) {
        if ("sin".equals(fn)) return Math.sin(x);
        if ("cos".equals(fn)) return Math.cos(x);
        if ("tan".equals(fn)) return Math.tan(x);
        if ("asin".equals(fn)) return Math.asin(x);
        if ("acos".equals(fn)) return Math.acos(x);
        if ("atan".equals(fn)) return Math.atan(x);
        if ("exp".equals(fn)) return Math.exp(x);
        if ("log".equals(fn)) return Math.log(x);
        if ("log10".equals(fn)) return Math.log10(x);
        if ("log1p".equals(fn)) return Math.log1p(x);
        if ("expm1".equals(fn)) return Math.expm1(x);
        if ("sinh".equals(fn)) return Math.sinh(x);
        if ("cosh".equals(fn)) return Math.cosh(x);
        if ("tanh".equals(fn)) return Math.tanh(x);
        if ("cbrt".equals(fn)) return Math.cbrt(x);
        if ("sqrt".equals(fn)) return Math.sqrt(x);
        throw new IllegalArgumentException("unknown unary function: " + fn);
    }

    /**
     * Evaluates {@code StrictMath.<fn>(x, y)}.
     *
     * @param fn one of {@link #BINARY}
     * @param x  the first argument
     * @param y  the second argument
     * @return the result
     */
    static double strictBinary(String fn, double x, double y) {
        if ("atan2".equals(fn)) return StrictMath.atan2(x, y);
        if ("pow".equals(fn)) return StrictMath.pow(x, y);
        if ("hypot".equals(fn)) return StrictMath.hypot(x, y);
        throw new IllegalArgumentException("unknown binary function: " + fn);
    }

    /**
     * Evaluates {@code Math.<fn>(x, y)} - the negative control.
     *
     * @param fn one of {@link #BINARY}
     * @param x  the first argument
     * @param y  the second argument
     * @return the result
     */
    static double mathBinary(String fn, double x, double y) {
        if ("atan2".equals(fn)) return Math.atan2(x, y);
        if ("pow".equals(fn)) return Math.pow(x, y);
        if ("hypot".equals(fn)) return Math.hypot(x, y);
        throw new IllegalArgumentException("unknown binary function: " + fn);
    }

    // ------------------------------------------------------------------

    /**
     * Squared eccentricities of the ellipsoids that carry the most traffic, so the probes include
     * the exact intermediates proj4j evaluates rather than only synthetic ones.
     *
     * <p>Values are computed from {@code a} and {@code rf} rather than copied, so a correction to
     * an ellipsoid definition cannot leave a stale constant here. They are only probe
     * <em>arguments</em>: nothing asserts they equal what {@code datum/Ellipsoid} holds, and this
     * class deliberately does not import it, so a concurrent edit there cannot red this test.
     */
    private static final double[] ES = buildEs();

    private static double[] buildEs() {
        // {inverse flattening} for WGS84/GRS80, Clarke 1866, Bessel 1841, Airy 1830, Krassovsky.
        double[] rf = {298.257223563, 298.257222101, 294.9786982, 299.1528128, 299.3249646, 298.3};
        double[] es = new double[rf.length + 1];
        for (int i = 0; i < rf.length; i++) {
            double f = 1.0 / rf[i];
            es[i] = f * (2.0 - f);
        }
        es[rf.length] = 0.0; // the sphere: es == 0 takes a different branch throughout proj4j
        return es;
    }

    /**
     * Fractional degrees taken from places where the corpus and the defect register put probes:
     * the {@code adams_ws2} antimeridian row, the tmerc seam, and the latitudes at which the
     * numerical core's helpers were measured worst.
     */
