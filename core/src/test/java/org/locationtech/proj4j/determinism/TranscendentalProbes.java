    /**
     * A 64-bit digest of a probe list's raw argument bits.
     *
     * <p>Committed alongside each golden section, and it is the guard that earns its keep: without
     * it, a probe list that generates <em>different arguments</em> on a different JDK produces a
     * flood of result mismatches whose message names an argument that looks perfectly reasonable.
     * That happened - see {@link #deg2rad(double)} - and cost real diagnosis time. With the digest,
     * the same situation fails once, immediately, saying the arguments moved.
     *
     * <p>FNV-1a over the eight bytes of each argument, most significant first. Any mixing function
     * would do; what matters is that it is defined here in Java arithmetic on {@code long}, which is
     * exact and reproducible on every JVM, rather than by a library whose implementation could vary.
     *
     * @param xs the argument list
     * @return the digest
     */
    static long digest(double[] xs) {
        long h = 0xcbf29ce484222325L;
        for (int i = 0; i < xs.length; i++) {
            long b = Double.doubleToRawLongBits(xs[i]);
            for (int shift = 56; shift >= 0; shift -= 8) {
                h ^= (b >>> shift) & 0xffL;
                h *= 0x100000001b3L;
            }
        }
        return h;
    }

    private static double[] toArray(List<Double> in) {
        double[] out = new double[in.size()];
        for (int i = 0; i < out.length; i++) {
            out[i] = in.get(i).doubleValue();
        }
        return out;
    }
